"""Experimental metadata for observed Merish MTA containers.

Synthetic lyrics, chords, granular timing and marker probes have been tested
on one Merish5+; marker exports generated by the app need device validation.
"""
from __future__ import annotations

import math
import re
from bisect import bisect_right
import xml.etree.ElementTree as ET
from pathlib import Path

from defusedxml import ElementTree as safe_et
from defusedxml.common import DefusedXmlException

from .models import MtaSlotMapping, Project
from .mta_reverse import _decode_colors_observed, _derive_observed_keystream, _raw_proprietary_section_body

_TYPES = {"click": "CLICK", "melody": "MELODIA", "drums": "DRUM", "bass": "BASS",
          "guitars": "GUITAR", "keyboards": "KEYBOARD", "orchestra": "ORCHESTRA",
          "winds": "WINDS", "choirs": "CORI", "other": "CORI"}


def extract_consistent_user_id(payloads: list[bytes]) -> str | None:
    """Extract an unambiguous identifier from bounded, safe XML attachments."""
    found = set()
    for raw in payloads:
        if len(raw) > 1_000_000 or not raw.lstrip().startswith(b"<?xml"):
            continue
        try:
            element = safe_et.fromstring(raw.rstrip(b"\x00 \r\n\t"))
        except (safe_et.ParseError, DefusedXmlException, ValueError):
            continue
        if element.tag != "MtxInfoData":
            continue
        identifier = element.findtext("Identity/UserId") or ""
        if not re.fullmatch(r"[0-9]{6}", identifier) or identifier == "000000":
            return None
        found.add(identifier)
    return next(iter(found)) if len(found) == 1 else None


def extract_consistent_syl_key(payloads: list[bytes]) -> str | None:
    """Recover the observed text transform only from consistent valid SYL attachments."""
    found = set()
    for raw in payloads:
        if len(raw) > 1_000_000 or not raw.startswith(b"ID3"):
            continue
        body = _raw_proprietary_section_body(raw, "COLORS")
        if not body:
            continue
        key = _derive_observed_keystream(body)
        decoded = _decode_colors_observed(body)
        if key is None or not decoded or not decoded.get("validated"):
            return None
        found.add(bytes(key).hex())
    return next(iter(found)) if len(found) == 1 else None


def validate_audio_only(project: Project) -> None:
    if not re.fullmatch(r"[0-9]{6}", project.merish_user_id or "") or project.merish_user_id == "000000":
        raise ValueError("Merish MTA sperimentale: inserire l'identificativo M-Live di sei cifre nei metadati del progetto")
    lines = [x for x in project.lyrics if not x.disabled and not x.deleted and x.text.strip()]
    chords = [x for x in project.chords if not x.excluded and not x.deleted and x.chord.strip()]
    markers = [x for x in project.markers if not x.disabled and not x.deleted]
    if lines or chords or markers:
        try:
            key = bytes.fromhex(project.merish_syl_key)
        except ValueError:
            key = b""
        if len(key) != 256 or len(set(key)) != 256:
            raise ValueError("Merish MTA: importa i metadati di un tuo MTA con testo prima di esportare lyrics, accordi o marker")
    if any(Path(x).suffix.lower() in {".syl", ".xml"} for x in project.preserved_attachments):
        raise ValueError("Merish MTA sperimentale non sostituisce allegati SYL/XML conservati di un progetto importato")


def _synchsafe(number: int) -> bytes:
    if not 0 <= number < 1 << 28:
        raise ValueError("ID3 tag too large")
    return bytes((number >> 21 & 127, number >> 14 & 127, number >> 7 & 127, number & 127))


def _event_stamp(time_ms: int) -> bytes:
    if not 0 <= time_ms < 256 * 60_000:
        raise ValueError("Merish MTA: gli eventi testuali devono trovarsi entro 256 minuti")
    centiseconds = (time_ms % 60_000) // 10
    digits = f"{centiseconds:04d}"
    return b"\n" + bytes(int(x) for x in digits[:2]) + b"\x1e" + bytes(int(x) for x in digits[2:]) + b"m"


def _synchronized_section(name: str, events: list[tuple[int, str]], key: bytes) -> bytes:
    if events[0][0] >= 60_000:
        raise ValueError("Merish MTA: il primo evento di testo o accordo deve iniziare entro il primo minuto")
    plain = bytearray()
    for index, (time_ms, text) in enumerate(events):
        if any(ord(char) < 32 or ord(char) == 127 for char in text):
            raise ValueError("Merish MTA: testo e accordi non possono contenere caratteri di controllo")
        try:
            payload = text.encode("latin-1")
        except UnicodeEncodeError as exc:
            raise ValueError("Merish MTA: testo e accordi richiedono caratteri Latin-1") from exc
        if len(payload) > 126:
            raise ValueError("Merish MTA: ogni evento di testo o accordo può contenere al massimo 126 caratteri")
        plain += _event_stamp(time_ms) + bytes(x ^ 0x30 for x in payload)
        if name == "LYRICS":
            plain += b"0"
        if index + 1 < len(events):
            next_minute = events[index + 1][0] // 60_000
            if next_minute > 255:
                raise ValueError("Merish MTA: eventi oltre 256 minuti non supportati")
            plain += b"=:k\x00" + bytes((next_minute,))
        else:
            plain += b"=:0=:" if name == "LYRICS" else b"=:"
    body = b"\x28\xb6\xa9" + bytes(value ^ key[(239 * i) % 256] ^ 10 for i, value in enumerate(plain))
    if len(body) >= 100_000:
        raise ValueError("Merish MTA: troppi eventi testuali per il formato sperimentale")
    header = f"{name}BEGININD0000211LYR{len(body):05d}\r\n".encode("ascii")
    footer = f"{len(header)-2+len(body):06d}{name}200\r\n".encode("ascii")
    return header + body + footer


def _colors_section(project: Project, duration_ms: int, key: bytes) -> bytes:
    """Encode the observed reset and highlight positions from timed lyric words."""
    lines = sorted((x for x in project.lyrics if not x.disabled and not x.deleted and x.text.strip()),
                   key=lambda line: line.time_ms)
    if duration_ms < 2560:
        raise ValueError("Merish MTA: la sincronizzazione granulare richiede almeno 2,56 secondi di audio")
    if any(not line.words for line in lines):
        raise ValueError("Merish MTA: tutte le righe attive richiedono parole sincronizzate")
    starts = [line.time_ms for line in lines]
    if any(a >= b for a, b in zip(starts, starts[1:])):
        raise ValueError("Merish MTA: le righe sincronizzate devono avere tempi iniziali distinti")
    prepared = []
    boundary_times = set()
    last_word_end = 0
    for i, line in enumerate(lines):
        if len(line.text) > 99:
            raise ValueError("Merish MTA: massimo 99 caratteri per riga con evidenziazione granulare")
        next_start = starts[i + 1] // 10 * 10 if i + 1 < len(lines) else duration_ms
        previous_time = line.time_ms // 10 * 10
        previous_position = 0
        cursor = 0
        prepared_words = []
        boundary_times.add(line.time_ms // 10 * 10)
        for wi, word in enumerate(line.words):
            text = word.text
            position = line.text.find(text, cursor) if text else -1
            if position < 0 or not text.strip():
                raise ValueError("Merish MTA: parole sincronizzate non corrispondenti al testo della riga")
            if any(char.isalnum() for char in line.text[cursor:position]):
                raise ValueError("Merish MTA: parole sincronizzate mancanti nel testo della riga")
            word_start, word_end = word.start_ms // 10 * 10, word.end_ms // 10 * 10
            if word_start < previous_time or word_end <= word_start or word.end_ms > next_start:
                raise ValueError("Merish MTA: tempi delle parole non validi, sovrapposti o oltre la riga")
            end_position = len(line.text) if wi == len(line.words) - 1 else position + len(text)
            subsegments = []
            if project.merish_lyric_highlight == "character" and word.syllables:
                if "".join(s.text for s in word.syllables) != text:
                    raise ValueError("Merish MTA: sillabe non corrispondenti alla parola")
                subposition = previous_position
                char_cursor = position
                syllable_time = word_start
                for si, syllable in enumerate(word.syllables):
                    sub_start, sub_end = syllable.start_ms // 10 * 10, syllable.end_ms // 10 * 10
                    if sub_start < syllable_time or sub_end <= sub_start or syllable.end_ms > word.end_ms:
                        raise ValueError("Merish MTA: tempi delle sillabe non validi o sovrapposti")
                    char_cursor += len(syllable.text)
                    target = end_position if si == len(word.syllables) - 1 else char_cursor
                    subsegments.append((sub_start, sub_end, subposition, target))
                    boundary_times.update((sub_start, sub_end))
                    subposition, syllable_time = target, sub_end
            else:
                subsegments.append((word_start, word_end, previous_position, end_position))
            prepared_words.append((word_start, word_end, previous_position, end_position, subsegments))
            boundary_times.update((word_start, word_end))
            previous_time, previous_position, cursor = word_end, end_position, position + len(text)
            last_word_end = max(last_word_end, word_end)
        if any(char.isalnum() for char in line.text[cursor:]):
            raise ValueError("Merish MTA: parole sincronizzate mancanti nel testo della riga")
        prepared.append(prepared_words)
    if last_word_end >= 256 * 60_000:
        raise ValueError("Merish MTA: gli eventi testuali devono trovarsi entro 256 minuti")
    end_time = min(duration_ms - 1, 256 * 60_000 - 1)
    until = min(end_time // 10 * 10, max(10240, last_word_end + 1240))
    interval = max(10, min(40, ((duration_ms - 10) // 255 // 10) * 10))
    interval = max(interval, math.ceil(until / 5000 / 10) * 10)
    times = set(range(0, until, interval))
    times.update(t for t in boundary_times if 0 <= t < duration_ms and t <= until)
    times = sorted(times)
    if len(times) < 256 or len(times) > 6664:
        raise ValueError("Merish MTA: numero di eventi di evidenziazione non supportato")
    starts_quantized = [t // 10 * 10 for t in starts]
    if len(set(starts_quantized)) != len(starts_quantized):
        raise ValueError("Merish MTA: righe troppo vicine per la precisione di 10 ms")
    records = []
    for index, time_ms in enumerate(times):
        li = bisect_right(starts_quantized, time_ms) - 1
        position = 0
        if li >= 0 and time_ms == starts_quantized[li]:
            position = 127
        elif li >= 0:
            for start, end, before, after, segments in prepared[li]:
                if time_ms < start:
                    break
                if time_ms >= end:
                    position = after
                    continue
                position = before
                if project.merish_lyric_highlight == "character":
                    for sub_start, sub_end, sub_before, sub_after in segments:
                        if time_ms < sub_start:
                            break
                        position = sub_after if time_ms >= sub_end else sub_before + (time_ms - sub_start) * (sub_after - sub_before) // (sub_end - sub_start)
                        if time_ms < sub_end:
                            break
                break
        digits = bytes(int(x) for x in f"{position:03d}")
        next_minute = times[index + 1] // 60_000 if index + 1 < len(times) else end_time // 60_000
        plain = _event_stamp(time_ms) + digits + b"=:k\x00" + bytes((next_minute,))
        records.append(bytes(value ^ key[(index - 17 * j) % 256] ^ 10 for j, value in enumerate(plain)))
    terminal = _event_stamp(end_time) + b"\x00\x00\x00=:0=:"
    index = len(records)
    records.append(bytes(value ^ key[(index - 17 * j) % 256] ^ 10 for j, value in enumerate(terminal)))
    body = b"\x28\xb6\xa9" + b"".join(records)
    header = f"COLORSBEGININD0000211LYR{len(body):05d}\r\n".encode("ascii")
    footer = f"{len(header)-2+len(body):06d}COLORS200\r\n".encode("ascii")
    return header + body + footer


def _midi_vlq(value: int) -> bytes:
    if not 0 <= value <= 0x0FFFFFFF:
        raise ValueError("Merish MTA: intervallo MIDI troppo lungo")
    data = [value & 0x7f]
    value >>= 7
    while value:
        data.append((value & 0x7f) | 0x80)
        value >>= 7
    return bytes(reversed(data))


def _experimental_marker_miditk(project: Project, duration_ms: int, key: bytes) -> bytes:
    """Encode absolute marker times in the device-tested synthetic MIDITK layout."""
    if len(key) != 256 or len(set(key)) != 256:
        raise ValueError("Merish MTA: metadati di testo non validi")
    if duration_ms <= 0 or not math.isfinite(project.bpm) or project.bpm <= 0:
        raise ValueError("Merish MTA: durata o BPM non validi per i marker")
    ppq = 480
    tempo = round(60_000_000 / project.bpm)
    if not 1 <= tempo <= 0xFFFFFF:
        raise ValueError("Merish MTA: BPM non rappresentabili nel MIDI")
    markers = sorted((x for x in project.markers if not x.disabled and not x.deleted), key=lambda x: x.time_ms)
    if not markers:
        raise ValueError("Merish MTA: nessun marker attivo")
    track = bytearray(b"\x00\xff\x51\x03" + tempo.to_bytes(3, "big"))
    previous_tick = 0
    for marker in markers:
        if marker.time_ms >= duration_ms:
            raise ValueError("Merish MTA: i marker devono precedere la fine del brano")
        if not marker.label.strip() or any(ord(char) < 32 or ord(char) == 127 for char in marker.label):
            raise ValueError("Merish MTA: nome marker vuoto o con caratteri di controllo")
        try:
            label = marker.label.encode("latin-1")
        except UnicodeEncodeError as exc:
            raise ValueError("Merish MTA: i nomi dei marker richiedono caratteri Latin-1") from exc
        tick = round(marker.time_ms * 1000 * ppq / tempo)
        track += _midi_vlq(tick - previous_tick) + b"\xff\x06" + _midi_vlq(len(label)) + label
        previous_tick = tick
    end_tick = round(duration_ms * 1000 * ppq / tempo)
    track += _midi_vlq(end_tick - previous_tick) + b"\xff\x2f\x00"
    midi = b"MThd\x00\x00\x00\x06\x00\x00\x00\x01" + ppq.to_bytes(2, "big") + b"MTrk" + len(track).to_bytes(4, "big") + bytes(track)
    body = bytes(value ^ key[(239 * (offset - 3)) % 256] ^ 10 ^ 0x30 for offset, value in enumerate(midi))
    if len(body) >= 100_000:
        raise ValueError("Merish MTA: troppi marker per il formato sperimentale")
    header = f"MIDITKBEGININD0000211LYR{len(body):05d}\r\n".encode("ascii")
    footer = f"{len(header)-2+len(body):06d}MIDITK200\r\n".encode("ascii")
    return header + body + footer


def _experimental_variable_marker_miditk(project: Project, duration_ms: int, key: bytes) -> bytes:
    """Build a MIDI tempo-map probe without enabling unverified device export."""
    from .musical_clock import MusicalClock

    if len(key) != 256 or len(set(key)) != 256:
        raise ValueError("Merish MTA: metadati di testo non validi")
    if duration_ms <= 0 or project.metronome_mode not in {"zones", "adaptive"}:
        raise ValueError("Merish MTA: mappa di tempo variabile non valida")
    if project.metronome_mode == "adaptive" and not project.adaptive_tempo_map:
        raise ValueError("Merish MTA: mappa di tempo adattiva mancante")
    clock = MusicalClock(project)
    origin = clock.quarter_at(0)
    ppq = 480

    def midi_tick(time_ms: float) -> int:
        return round((clock.quarter_at(time_ms) - origin) * ppq)

    active = clock.sections[max(0, bisect_right(clock.times, 0) - 1)]
    sections = [(0.0, active)] + [(section["at"], section) for section in clock.sections if 0 < section["at"] < duration_ms]
    events = []
    last_tempo_tick = -1
    for time_ms, section in sections:
        tempo = round(60_000_000 / section["quarter_bpm"])
        tick = midi_tick(time_ms)
        if not 1 <= tempo <= 0xFFFFFF or tick <= last_tempo_tick:
            raise ValueError("Merish MTA: cambi di tempo non rappresentabili nella griglia MIDI")
        events.append((tick, 0, b"\xff\x51\x03" + tempo.to_bytes(3, "big")))
        last_tempo_tick = tick
    markers = [x for x in project.markers if not x.disabled and not x.deleted]
    if not markers:
        raise ValueError("Merish MTA: nessun marker attivo")
    for marker in markers:
        if marker.time_ms >= duration_ms:
            raise ValueError("Merish MTA: i marker devono precedere la fine del brano")
        if not marker.label.strip() or any(ord(char) < 32 or ord(char) == 127 for char in marker.label):
            raise ValueError("Merish MTA: nome marker vuoto o con caratteri di controllo")
        try:
            label = marker.label.encode("latin-1")
        except UnicodeEncodeError as exc:
            raise ValueError("Merish MTA: i nomi dei marker richiedono caratteri Latin-1") from exc
        events.append((midi_tick(marker.time_ms), 1, b"\xff\x06" + _midi_vlq(len(label)) + label))
    end_tick = midi_tick(duration_ms)
    events.append((end_tick, 2, b"\xff\x2f\x00"))
    events.sort(key=lambda event: (event[0], event[1]))
    track = bytearray()
    previous_tick = 0
    for tick, _, data in events:
        track += _midi_vlq(tick - previous_tick) + data
        previous_tick = tick
    midi = b"MThd\x00\x00\x00\x06\x00\x00\x00\x01" + ppq.to_bytes(2, "big") + b"MTrk" + len(track).to_bytes(4, "big") + bytes(track)
    body = bytes(value ^ key[(239 * (offset - 3)) % 256] ^ 10 ^ 0x30 for offset, value in enumerate(midi))
    if len(body) >= 100_000:
        raise ValueError("Merish MTA: troppi eventi di tempo o marker per la prova")
    header = f"MIDITKBEGININD0000211LYR{len(body):05d}\r\n".encode("ascii")
    footer = f"{len(header)-2+len(body):06d}MIDITK200\r\n".encode("ascii")
    return header + body + footer


def build_minimal_syl(project: Project, duration_ms: int) -> bytes:
    """Create experimental SYL metadata, lyrics, highlighting, markers and chords."""
    validate_audio_only(project)
    frames = bytearray()
    metadata = [("TIT2", project.title), ("TPE1", project.artist or " "),
                ("TBPM", str(round(project.bpm)))]
    if project.key.strip():
        metadata.append(("TKEY", project.key.strip()))
    metadata.append(("TLEN", str(duration_ms)))
    for name, value in metadata:
        try:
            payload = b"\x00" + value.encode("latin-1")
        except UnicodeEncodeError:
            payload = b"\x01" + value.encode("utf-16")
        frames += name.encode("ascii") + len(payload).to_bytes(4, "big") + b"\x00\x00" + payload
    lines = sorted(((x.time_ms, x.text) for x in project.lyrics if not x.disabled and not x.deleted and x.text.strip()), key=lambda event: event[0])
    chords = sorted(((x.time_ms, x.chord) for x in project.chords if not x.excluded and not x.deleted and x.chord.strip()), key=lambda event: event[0])
    markers = [x for x in project.markers if not x.disabled and not x.deleted]
    if lines or chords or markers:
        key = bytes.fromhex(project.merish_syl_key)
        if any(time >= duration_ms for time, _ in lines + chords):
            raise ValueError("Merish MTA: gli eventi testuali devono precedere la fine del brano")
        if lines:
            frames += _synchronized_section("LYRICS", lines, key)
            if any(x.words for x in project.lyrics if not x.disabled and not x.deleted and x.text.strip()):
                frames += _colors_section(project, duration_ms, key)
        if markers:
            frames += _experimental_marker_miditk(project, duration_ms, key)
        if chords:
            frames += _synchronized_section("CHORDS", chords, key)
    return b"ID3\x03\x00\x00" + _synchsafe(len(frames)) + bytes(frames)


def build_settings_xml(project: Project, slots: list[MtaSlotMapping], duration_ms: int) -> bytes:
    validate_audio_only(project)
    if project.target == "MTA8":
        if len(slots) != 8:
            raise ValueError("Merish Xynthia2 MTA8 richiede esattamente 8 slot fisici")
    elif project.target != "MTA16" or not 1 <= len(slots) <= 16:
        raise ValueError("Merish MTA richiede MTA8 o MTA16 con massimo 16 slot fisici")
    if [slot.slot for slot in slots] != list(range(1, len(slots) + 1)):
        raise ValueError("Merish MTA richiede slot fisici consecutivi")
    root = ET.Element("MtxInfoData", {"version": "0.0"})
    identity = ET.SubElement(root, "Identity")
    for key, value in (("UserId", project.merish_user_id), ("AProId", "0")):
        ET.SubElement(identity, key).text = value
    general = ET.SubElement(root, "General")
    # Merish5+ skipped approximately four seconds on the otherwise identical
    # 2,000,000-us probe. Zero preserved the complete audio from the beginning.
    # The project's generated click/pre-roll is already carried as audio.
    for key, value in (("BaseKey", "26"), ("BaseBpm", str(round(project.bpm))),
                       ("DurataSec", str(max(1, duration_ms // 1000))), ("PreCntUSec", "0")):
        ET.SubElement(general, key).text = value
    ET.SubElement(root, "TrkVideo")
    tracks = ET.SubElement(root, "TrkAudio")
    # The verified Y4 probe used 281 flags. Longer outputs need at least one
    # flag per second; longer durations and other track counts require hardware validation.
    note_on = ";".join(["1"] * max(281, math.ceil(duration_ms / 1000) + 1))
    for slot in slots:
        track = ET.SubElement(tracks, "Track")
        values = (("Num", str(slot.slot)), ("Nome", slot.name), ("Type", _TYPES.get(slot.type, "CORI")),
                  ("Routing", "2" if slot.type == "click" else "1"), ("Volume", "100"),
                  ("MuteSolo", "0"), ("NoteOn", note_on))
        for key, value in values:
            ET.SubElement(track, key).text = value
    return ET.tostring(root, encoding="utf-8", xml_declaration=True) + b"\n" + bytes(1000)
